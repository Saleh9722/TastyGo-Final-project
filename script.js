function subscribe() {
  const input = $("newsletterEmail");

  if (!input.value.trim()) {
    alert(t("Please enter your email."));
    return;
  }

  if (!input.reportValidity()) {
    return;
  }

  alert(
    `${t("Thank you")}!

${t("You are now subscribed.")}`,
  );

  input.value = "";
}

